#!/usr/bin/env node
// The review's inventory reconciled with the current app. Joins the baseline
// inventory (docs/inventory-baseline.json) and a fresh scan of src/
// (scripts/inventory-scan.mjs) with the classification in
// src/inventoryMap.ts, the shared actions (src/actionDefs.ts) and the route
// ledger (src/routeLedger.ts), and writes docs/INVENTORY_RECONCILIATION.md.
// src/inventoryMap.test.ts fails while that file is stale or anything is
// unclassified. Run: node scripts/inventory-reconcile.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanInventory } from './inventory-scan.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const norm = s => String(s ?? '').replace(/\s+/g, ' ').trim();

export async function reconcile(root = ROOT) {
  const { FILES, REMOVED, COMMAND_ONLY, ACTIONS_RECONCILED } = await import(path.join(root, 'src/inventoryMap.ts'));
  const { ACTION_DEFS, actionLabel } = await import(path.join(root, 'src/actionDefs.ts'));
  const { ROUTE_BY_ID } = await import(path.join(root, 'src/routeLedger.ts'));
  const baseline = JSON.parse(fs.readFileSync(path.join(root, 'docs/inventory-baseline.json'), 'utf8'));
  const scan = scanInventory(root);
  const files = [...new Set([...scan.controls.map(c => c.file), ...scan.actions.map(a => a.file)])].sort();
  const count = (list, f) => list.filter(x => x.file === f).length;
  const fileRows = files.map(f => ({ file: f, ...(FILES[f] ?? { class: 'UNCLASSIFIED' }), controls: count(scan.controls, f), actions: count(scan.actions, f),
    baselineControls: count(baseline.controls, f), baselineActions: count(baseline.actions, f) }));
  const baseFiles = [...new Set([...baseline.controls.map(c => c.file), ...baseline.actions.map(a => a.file)])];
  const gone = baseFiles.filter(f => !files.includes(f)).sort().map(f => ({ file: f, reason: REMOVED[f] ?? null }));
  // Each baseline action: still there, now a shared action, moved, or reworded.
  const here = new Set(scan.actions.map(a => `${a.file}::${norm(a.label)}`));
  const elsewhere = new Map(scan.actions.map(a => [norm(a.label), a.file]));
  const byRegistry = d => [d.palette, d.go, d.key, d.menu].filter(Boolean);
  const actionRows = baseline.actions.map(a => {
    const label = norm(a.label), key = norm(a.key).replace(/^'|'$/g, '');
    if (here.has(`${a.file}::${label}`)) return { ...a, status: 'kept', now: a.file };
    const def = ACTION_DEFS.find(d => byRegistry(d).includes(key)) ?? ACTION_DEFS.find(d => [d.label, ...Object.values(d.labels ?? {})].includes(label));
    if (def) return { ...a, status: 'shared action', now: `actionDefs.ts \`${def.id}\` “${actionLabel(def)}” → ${def.route}` };
    if (elsewhere.has(label)) return { ...a, status: 'moved', now: elsewhere.get(label) };
    if (ACTIONS_RECONCILED[a.id]) return { ...a, status: 'reconciled', now: ACTIONS_RECONCILED[a.id] };
    return { ...a, status: 'UNRECONCILED', now: '' };
  });
  const routesMissing = fileRows.flatMap(r => (r.routes ?? []).filter(id => !ROUTE_BY_ID[id]).map(id => `${r.file}: ${id}`))
    .concat(COMMAND_ONLY.filter(c => c.route && !ROUTE_BY_ID[c.route]).map(c => `${c.command}: ${c.route}`));
  return { baseline: baseline.baseline, scan, fileRows, gone, actionRows, commandOnly: COMMAND_ONLY, routesMissing,
    stale: Object.keys(FILES).filter(f => !files.includes(f)) };
}

export function renderReconciliation(d) {
  const cell = s => norm(s).replace(/\|/g, '\\|');
  const by = k => d.fileRows.filter(r => r.class === k);
  const sum = (rows, k) => rows.reduce((n, r) => n + r[k], 0);
  const status = s => d.actionRows.filter(r => r.status === s).length;
  const lines = [
    '# Inventory reconciliation',
    '',
    'Generated by `node scripts/inventory-reconcile.mjs` from the baseline inventory (`docs/inventory-baseline.json`,',
    `baseline \`${d.baseline.slice(0, 8)}\`), a fresh scan of \`src/\` by the same method (\`scripts/inventory-scan.mjs\`) and the`,
    'classification in `src/inventoryMap.ts`; `src/inventoryMap.test.ts` fails while this file is stale or any file, action or',
    'command is unclassified (plan completion L4, matrix N1). Static evidence, like the review’s: one source site is not one',
    'runtime button. The route ledger’s walks ([ROUTE_LEDGER.md](ROUTE_LEDGER.md)) are the clicked evidence for each row named here.',
    '',
    '## Summary',
    '',
    `- **Now:** ${d.scan.controls.length} control sites and ${d.scan.actions.length} action objects in ${d.fileRows.length} files.`,
    `- **Classes:** ${by('capability').length} capability files (${sum(by('capability'), 'controls')} controls) belong to ledger rows; ${by('primitive').length} shared primitives (${sum(by('primitive'), 'controls')}); ${by('registry').length} action tables; ${by('harness').length} harness files.`,
    `- **Baseline actions (${d.actionRows.length}):** ${status('kept')} kept where they were, ${status('shared action')} now shared actions (actionDefs.ts), ${status('moved')} moved, ${status('reconciled')} renamed or rebuilt (each explained), ${status('UNRECONCILED')} unreconciled.`,
    `- **Removed files:** ${d.gone.length}. **Command-only ways in** (slash commands, in-surface keys, tray): ${d.commandOnly.length}, each with its visible route.`,
    '',
    '## Files',
    '',
    '| File | Class | Ledger rows | Controls (baseline → now) | Actions (baseline → now) | Note |', '|---|---|---|---|---|---|',
    ...d.fileRows.map(r => `| \`${r.file.replace(/^src\//, '')}\` | ${r.class} | ${(r.routes ?? []).map(x => `\`${x}\``).join(', ') || '—'} | ${r.baselineControls} → ${r.controls} | ${r.baselineActions} → ${r.actions} | ${cell(r.note ?? '')} |`),
    '',
    '## Removed since the review',
    '',
    '| File | Why |', '|---|---|',
    ...d.gone.map(g => `| \`${g.file.replace(/^src\//, '')}\` | ${cell(g.reason ?? 'UNEXPLAINED')} |`),
    '',
    '## Command-only ways in, and their visible routes',
    '',
    '| Surface | Command or key | Visible route | Ledger row |', '|---|---|---|---|',
    ...d.commandOnly.map(c => `| ${c.surface} | ${cell(c.command)} | ${cell(c.visible)} | ${c.route ? `\`${c.route}\`` : '—'} |`),
    '',
    `## The review’s ${d.actionRows.length} action objects`,
    '',
    '| ID | Was | Label | Status | Now |', '|---|---|---|---|---|',
    ...d.actionRows.map(a => `| ${a.id} | \`${a.file.replace(/^src\//, '')}:${a.line}\` | ${cell(a.label).slice(0, 90)} | ${a.status} | ${cell(a.now).replace(/^src\//, '')} |`),
  ];
  return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const d = await reconcile();
  const out = path.join(ROOT, 'docs/INVENTORY_RECONCILIATION.md');
  fs.writeFileSync(out, renderReconciliation(d));
  const bad = [...d.fileRows.filter(r => r.class === 'UNCLASSIFIED').map(r => r.file), ...d.actionRows.filter(a => a.status === 'UNRECONCILED').map(a => a.id), ...d.gone.filter(g => !g.reason).map(g => g.file), ...d.routesMissing, ...d.stale];
  console.log(`inventory-reconcile: wrote ${out}${bad.length ? `; ${bad.length} problems: ${bad.join(', ')}` : ''}`);
}
