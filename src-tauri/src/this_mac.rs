//! One provider-neutral machine note, derived from the build slot source.
//! Generation never changes a provider's own context files.

use crate::remote_session::RunnerSetting;
use std::path::{Path, PathBuf};

pub(crate) const FILE_NAME: &str = "this-mac.md";

/// The note's size limit, in bytes.
const MAX_BYTES: usize = 3_000;

/// Notes the last [`ensure_file`] for their folder wrote or confirmed. A
/// failed generation drops its note from here even when the old file can't
/// be removed (an unwritable folder), so `build_slots::turn_env` never points
/// a turn at a note Hollow couldn't bring up to date (#1234 review).
static CURRENT: std::sync::Mutex<Vec<PathBuf>> = std::sync::Mutex::new(Vec::new());

/// Whether `path` is a note the last [`ensure_file`] for its folder wrote or
/// confirmed, and it is still there.
pub(crate) fn is_current(path: &Path) -> bool {
    path.is_file()
        && CURRENT
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
            .iter()
            .any(|p| p == path)
}

fn mark(path: &Path, current: bool) {
    let mut list = CURRENT
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    list.retain(|p| p != path);
    if current {
        list.push(path.to_path_buf());
    }
}

/// Marks a hand-written note current, for tests outside this module.
#[cfg(test)]
pub(crate) fn mark_current_for_test(path: &Path) {
    mark(path, true);
}

pub(crate) struct Facts {
    cores: Option<usize>,
    memory_bytes: Option<u64>,
    slots: usize,
    caps: Vec<(&'static str, &'static str)>,
    slot_dir: PathBuf,
    targets: PathBuf,
    /// Read by the same rule placement uses (`configured_runner`), so the
    /// note never names a runner Hollow treats as none (J4 review).
    runner: RunnerSetting,
}

impl Facts {
    pub(crate) fn detect() -> Self {
        Self {
            cores: std::thread::available_parallelism().ok().map(usize::from),
            memory_bytes: memory_bytes(),
            slots: crate::build_slots::SLOTS,
            caps: crate::build_slots::CAPS.to_vec(),
            slot_dir: crate::build_slots::slot_dir(),
            targets: crate::instance::cache_sibling("build-targets"),
            runner: crate::remote_session::configured_runner_setting(),
        }
    }
}

#[cfg(target_os = "macos")]
fn memory_bytes() -> Option<u64> {
    let mut bytes = 0_u64;
    let mut len = std::mem::size_of::<u64>();
    // SAFETY: the NUL-terminated name and writable output/length pointers
    // are valid for this read-only sysctl call; no new value is supplied.
    let rc = unsafe {
        libc::sysctlbyname(
            c"hw.memsize".as_ptr(),
            (&mut bytes as *mut u64).cast(),
            &mut len,
            std::ptr::null_mut(),
            0,
        )
    };
    (rc == 0 && len == std::mem::size_of::<u64>()).then_some(bytes)
}

#[cfg(not(target_os = "macos"))]
fn memory_bytes() -> Option<u64> {
    let meminfo = std::fs::read_to_string("/proc/meminfo").ok()?;
    let line = meminfo
        .lines()
        .find_map(|line| line.strip_prefix("MemTotal:"))?;
    line.split_whitespace()
        .next()?
        .parse::<u64>()
        .ok()?
        .checked_mul(1024)
}

// Paths may contain Markdown or line breaks. Keep facts on their own line
// and bound their contribution, including unusually long home folders.
fn inline(value: &str) -> String {
    let mut bytes = 0;
    value
        .chars()
        .take_while(|c| {
            bytes += c.len_utf8();
            bytes <= 360
        })
        .map(|c| {
            if c.is_control()
                || matches!(c, '`' | '\u{2028}' | '\u{2029}' | '\u{2013}' | '\u{2014}')
            {
                '?'
            } else {
                c
            }
        })
        .collect()
}

const DO_NOT_EDIT: &str = "Generated by Hollow from its build slot settings. Do not edit.";
const DEV_SERVER: &str =
    "- A dev server uses `hollow-slot --dev-server <cmd>` and this turn's `PORT` / `PW_PORT`.\n";

fn caps_section(caps: &[(&str, &str)]) -> String {
    let mut text = String::from("\n## Toolchain caps\n\n");
    for (key, value) in caps {
        text.push_str(&format!("- `{key}={value}`\n"));
    }
    text
}

/// The note for this Mac: its hardware, folders, runner and caps.
pub(crate) fn render(facts: &Facts) -> String {
    let cores = facts
        .cores
        .map(|n| n.to_string())
        .unwrap_or_else(|| "unknown".into());
    let memory = facts
        .memory_bytes
        .map(|n| format!("{} GiB", n / (1024 * 1024 * 1024)))
        .unwrap_or_else(|| "unknown".into());
    let mut text = format!(
        "# This Mac\n\n{DO_NOT_EDIT}\n\n\
         - Logical cores: {cores}. Physical memory: {memory}.\n\
         - At most {} toolchain slots at once; one Rust build and one dev server machine-wide.\n",
        facts.slots,
    );
    match &facts.runner {
        RunnerSetting::Host(host) => text.push_str(&format!(
            "- Run builds and tests with `hollow-slot <cmd>`; it chooses this Mac or the configured runner, `{}`. Gates and suites normally run there.\n\
             - `--here` forces this Mac; `--remote` requests the runner and falls back here when it can't be reached.\n",
            inline(host)
        )),
        RunnerSetting::Off => text.push_str(
            "- No runner configured. Run builds and tests with `hollow-slot <cmd>`; they run on this Mac.\n",
        ),
        RunnerSetting::Invalid => text.push_str(
            "- The runner setting is not an SSH host name, so Hollow uses no runner. Run builds and tests with `hollow-slot <cmd>`; they run on this Mac.\n",
        ),
    }
    text.push_str(DEV_SERVER);
    text.push_str(&format!(
        "- Slot locks: `{}`. Per-worktree build targets: `{}`.\n\
         - Use this turn's `CARGO_TARGET_DIR` when supplied.\n",
        inline(&facts.slot_dir.to_string_lossy()),
        inline(&facts.targets.to_string_lossy()),
    ));
    text.push_str(&caps_section(&facts.caps));
    text
}

/// The note remote preparation installs on the runner. Its own text, not
/// this Mac's with words swapped (J4 review): a remote session runs with
/// `HOLLOW_SLOT_REMOTE=off`, so builds run where it is and there is no
/// further runner. Hollow doesn't detect the runner's hardware, so it says
/// unknown instead of borrowing this Mac's. Paths are the supervisor's
/// variables for this turn.
pub(crate) fn runner_note() -> String {
    let mut text = format!(
        "# This machine (remote session)\n\n{DO_NOT_EDIT}\n\n\
         - This session already runs on Hollow's remote runner. Builds and tests run here; there is no further runner.\n\
         - Logical cores: unknown. Physical memory: unknown. Hollow does not detect the runner's hardware.\n\
         - At most {} toolchain slots at once; one Rust build and one dev server at a time on this machine.\n\
         - Run builds and tests with `hollow-slot <cmd>`. Routing is off here (`HOLLOW_SLOT_REMOTE=off`), so every command runs on this machine, `--remote` included.\n",
        crate::build_slots::SLOTS,
    );
    text.push_str(DEV_SERVER);
    text.push_str(
        "- Slot locks: `$HOLLOW_BUILD_SLOT_DIR`. This session's build target: `$CARGO_TARGET_DIR`. Both name folders on this machine.\n",
    );
    text.push_str(&caps_section(&crate::build_slots::CAPS));
    text
}

/// Returns whether the note changed. Callers choose the folder, so tests
/// write only into their own temporary directory. When the note can't be
/// brought up to date the old one is removed, so no turn reads a stale note:
/// `build_slots::turn_env` exports `HOLLOW_THIS_MAC` only for a note this
/// function last wrote or confirmed ([`is_current`]), so a stale note whose
/// removal also failed is never exported either.
pub(crate) fn ensure_file(dir: &Path, facts: &Facts) -> Result<bool, String> {
    let path = dir.join(FILE_NAME);
    let result = write_note(dir, &path, &render(facts));
    mark(&path, result.is_ok());
    if result.is_err() {
        let _ = std::fs::remove_file(&path);
    }
    result
}

fn write_note(dir: &Path, path: &Path, text: &str) -> Result<bool, String> {
    if text.len() > MAX_BYTES {
        return Err(format!("generated machine note exceeds {MAX_BYTES} bytes"));
    }
    if std::fs::read_to_string(path).ok().as_deref() == Some(text) {
        return Ok(false);
    }
    std::fs::create_dir_all(dir).map_err(|e| format!("create machine note folder: {e}"))?;
    crate::vault::atomic_write(path, text.as_bytes())?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::remote_session::runner_setting;

    fn facts() -> Facts {
        Facts {
            cores: Some(18),
            memory_bytes: Some(48 * 1024 * 1024 * 1024),
            slots: crate::build_slots::SLOTS,
            caps: crate::build_slots::CAPS.to_vec(),
            slot_dir: "/tmp/slots".into(),
            targets: "/cache/targets".into(),
            runner: RunnerSetting::Host("mini".into()),
        }
    }

    #[test]
    fn note_uses_the_slot_source_and_is_deterministic_and_bounded() {
        let facts = facts();
        let text = render(&facts);
        assert_eq!(text, render(&facts));
        assert!(text.len() <= MAX_BYTES);
        assert!(text.contains("Logical cores: 18. Physical memory: 48 GiB."));
        assert!(text.contains(&format!(
            "At most {} toolchain slots",
            crate::build_slots::SLOTS
        )));
        for (key, value) in crate::build_slots::CAPS {
            assert!(text.contains(&format!("`{key}={value}`")));
        }
        assert!(!text.contains(['\u{2013}', '\u{2014}']));
    }

    /// Each runner setting gets its own wording on this Mac.
    #[test]
    fn the_local_note_names_the_runner_placement_uses() {
        let mut facts = facts();
        let host = render(&facts);
        assert!(host.contains("chooses this Mac or the configured runner, `mini`"));
        assert!(host.contains("`--here` forces this Mac; `--remote` requests the runner"));
        facts.runner = RunnerSetting::Off;
        let off = render(&facts);
        assert!(off.contains("No runner configured."), "{off}");
        assert!(!off.contains("--remote") && !off.contains("configured runner"));
        facts.runner = runner_setting(None, Some("user:secret@host"));
        let invalid = render(&facts);
        assert!(invalid.contains("not an SSH host name, so Hollow uses no runner"));
        assert!(!invalid.contains("secret") && !invalid.contains("--remote"));
    }

    /// J4 review: the note reads the runner with placement's own rule
    /// (`remote_session::runner_setting`, which `configured_runner` uses),
    /// so a value placement treats as none is never named as a runner.
    #[test]
    fn config_is_only_a_host_placement_accepts() {
        assert_eq!(
            runner_setting(None, Some("# runner\n\n user@mini # runner\nignored")),
            RunnerSetting::Host("user@mini".into())
        );
        for text in ["off", "local", "none", "", "# only", " off "] {
            assert_eq!(
                runner_setting(None, Some(text)),
                RunnerSetting::Off,
                "{text}"
            );
        }
        assert_eq!(runner_setting(None, None), RunnerSetting::Off);
        for text in [
            "host:22",
            "-J",
            "-oProxyCommand=x",
            "user:secret@host",
            "mini; echo secret",
            "mini\tbad",
            "alias%name",
            "alias+name",
        ] {
            assert_eq!(
                runner_setting(None, Some(text)),
                RunnerSetting::Invalid,
                "{text}"
            );
            assert_eq!(
                runner_setting(Some(text), None),
                RunnerSetting::Invalid,
                "{text}"
            );
        }
        // The environment wins when set, even empty, and is trimmed.
        assert_eq!(runner_setting(Some(""), Some("mini")), RunnerSetting::Off);
        assert_eq!(
            runner_setting(Some(" other\n"), Some("off")),
            RunnerSetting::Host("other".into())
        );
        // Whatever is named passes placement's host check.
        for text in ["mini", "user@mini.local", "a_b-c.d"] {
            match runner_setting(None, Some(text)) {
                RunnerSetting::Host(host) => {
                    assert!(crate::remote_session::valid_host(&host), "{host}")
                }
                other => panic!("{text}: {other:?}"),
            }
        }
    }

    #[test]
    fn ensure_writes_only_a_changed_note_to_the_supplied_temp_folder() {
        let temp = tempfile::Builder::new()
            .prefix("this-mac-ensure-")
            .tempdir()
            .unwrap();
        let dir = temp.path().join("bin");
        let mut facts = facts();
        assert!(ensure_file(&dir, &facts).unwrap());
        let path = dir.join(FILE_NAME);
        let stamp = std::fs::metadata(&path).unwrap().modified().unwrap();
        assert!(!ensure_file(&dir, &facts).unwrap());
        assert_eq!(std::fs::metadata(&path).unwrap().modified().unwrap(), stamp);
        facts.runner = RunnerSetting::Off;
        assert!(ensure_file(&dir, &facts).unwrap());
        assert_eq!(std::fs::read_to_string(path).unwrap(), render(&facts));
    }

    /// J4 review: a failed generation removes the old note, and a turn then
    /// gets no `HOLLOW_THIS_MAC` (it still gets its caps and the slot tool).
    #[test]
    fn a_failed_generation_removes_the_stale_note_and_its_variable() {
        let temp = tempfile::Builder::new()
            .prefix("this-mac-stale-")
            .tempdir()
            .unwrap();
        let dir = temp.path().join("bin");
        let has_var = |dir: &Path| {
            crate::build_slots::turn_env(Some(dir), None)
                .iter()
                .any(|(key, _)| key == "HOLLOW_THIS_MAC")
        };
        assert!(!has_var(dir.as_path()), "no note yet");
        assert!(ensure_file(&dir, &facts()).unwrap());
        assert!(has_var(dir.as_path()));
        let mut big = facts();
        big.caps = vec![("A_CAP_NAME_LONG_ENOUGH_TO_OVERFLOW_THE_NOTE", "0123456789"); 100];
        assert!(ensure_file(&dir, &big)
            .unwrap_err()
            .contains("exceeds 3000 bytes"));
        assert!(!dir.join(FILE_NAME).exists(), "the stale note is gone");
        let env = crate::build_slots::turn_env(Some(&dir), None);
        assert!(!env.iter().any(|(key, _)| key == "HOLLOW_THIS_MAC"));
        assert!(env.iter().any(|(key, _)| key == "PATH"));
        for (key, value) in crate::build_slots::CAPS {
            assert!(env.iter().any(|(k, v)| k == key && v == value), "{key}");
        }
    }

    /// #1234 review: in a folder Hollow can't write, a failed generation
    /// can't remove the old note either. The file stays, but no turn is
    /// pointed at it.
    #[cfg(unix)]
    #[test]
    fn a_stale_note_that_cannot_be_removed_is_not_exported() {
        use std::os::unix::fs::PermissionsExt;
        let temp = tempfile::Builder::new()
            .prefix("this-mac-locked-")
            .tempdir()
            .unwrap();
        let dir = temp.path().join("bin");
        let note = dir.join(FILE_NAME);
        assert!(ensure_file(&dir, &facts()).unwrap());
        assert!(is_current(&note));
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o555)).unwrap();
        let mut big = facts();
        big.caps = vec![("A_CAP_NAME_LONG_ENOUGH_TO_OVERFLOW_THE_NOTE", "0123456789"); 100];
        let failed = ensure_file(&dir, &big);
        let left = note.exists();
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o755)).unwrap();
        assert!(failed.is_err());
        assert!(left, "a read-only folder keeps the old note");
        assert!(!is_current(&note));
        assert!(!crate::build_slots::turn_env(Some(&dir), None)
            .iter()
            .any(|(key, _)| key == "HOLLOW_THIS_MAC"));
        // The next successful generation (the text is unchanged, so it only
        // confirms the note) exports it again.
        assert!(!ensure_file(&dir, &facts()).unwrap());
        assert!(is_current(&note));
    }

    #[test]
    fn paths_cannot_inject_lines_and_long_paths_remain_bounded() {
        let mut facts = facts();
        facts.targets = "a`\nmalicious".into();
        assert!(render(&facts).contains("`a??malicious`"));
        facts.targets = "界".repeat(1000).into();
        facts.slot_dir = "界".repeat(1000).into();
        let temp = tempfile::Builder::new()
            .prefix("this-mac-long-")
            .tempdir()
            .unwrap();
        assert!(render(&facts).len() <= MAX_BYTES);
        assert!(ensure_file(temp.path(), &facts).unwrap());
    }

    /// J4 review: the runner's note is its own text. It says builds run
    /// there with no further runner, and nothing of this Mac's routing.
    #[test]
    fn remote_note_says_what_holds_on_the_runner() {
        let note = runner_note();
        assert!(note.starts_with("# This machine (remote session)\n"));
        assert!(note.contains("already runs on Hollow's remote runner"));
        assert!(note.contains("Builds and tests run here; there is no further runner."));
        assert!(note.contains("Logical cores: unknown. Physical memory: unknown."));
        assert!(note.contains("Routing is off here (`HOLLOW_SLOT_REMOTE=off`)"));
        assert!(note.contains("`$HOLLOW_BUILD_SLOT_DIR`"));
        assert!(note.contains("`$CARGO_TARGET_DIR`"));
        for local in [
            "this Mac",
            "This Mac",
            "configured runner",
            "chooses",
            "--here",
            "requests the runner",
            "falls back",
        ] {
            assert!(!note.contains(local), "{local}");
        }
        assert!(note.is_ascii() && note.len() <= MAX_BYTES);
        for (key, value) in crate::build_slots::CAPS {
            assert!(note.contains(&format!("`{key}={value}`")));
        }
        assert!(crate::remote_session::REMOTE_RUN_PL
            .contains("$ENV{HOLLOW_THIS_MAC} = \"$root/bin/this-mac.md\""));
        assert!(crate::remote_session::REMOTE_RUN_PL.contains("$ENV{HOLLOW_SLOT_REMOTE} = 'off'"));
    }
}
